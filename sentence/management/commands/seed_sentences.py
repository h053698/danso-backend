class Command(BaseCommand):
    help = "기본 문장 세트를 DB에 시딩합니다 (이미 존재하면 건너뜀)"

    def handle(self, *args, **options):
        # 시스템 유저 확보 (없으면 생성)
        user, created = GameUser.objects.get_or_create(
            username=SYSTEM_USER["username"],
            defaults={
                "nickname": SYSTEM_USER["nickname"],
                "email": SYSTEM_USER["email"],
            },
        )
        if created:
            self.stdout.write(self.style.SUCCESS(f"시스템 유저 생성: {user.nickname}"))
        else:
            self.stdout.write(f"시스템 유저 확인: {user.nickname}")

        created_count = 0
        skipped_count = 0

        for pack_data in PACKS:
            exists = SentencePack.objects.filter(
                name=pack_data["name"], author=user
            ).exists()
            if exists:
                skipped_count += 1
                self.stdout.write(f"  건너뜀: {pack_data['name']}")
                continue

            SentencePack.objects.create(
                name=pack_data["name"],
                level=pack_data["level"],
                sentences=SEP.join(pack_data["sentences"]),
                author=user,
                original_author="단소봇",
            )
            created_count += 1
            self.stdout.write(
                self.style.SUCCESS(f"  생성: [{pack_data['level']}] {pack_data['name']}")
            )

        self.stdout.write(
            self.style.SUCCESS(
                f"\n완료 — 생성 {created_count}개 / 건너뜀 {skipped_count}개"
            )
        )
